import { chromium, expect } from "@playwright/test";
import assert from "node:assert/strict";
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1050 } });
page.on("dialog", d => d.accept());
try {
  await page.goto(process.env.EDITOR_TEST_URL || "http://127.0.0.1:5173/editor");
  await page.locator('input[type="file"]').first().setInputFiles({ name: "interactions.html", mimeType: "text/html", buffer: Buffer.from('<!doctype html><html><head><style>body{margin:0;font-family:Arial}main{padding:40px}p{width:300px}img{width:120px;height:80px}</style></head><body><main><p>Double click this text</p><img src="data:image/svg+xml,%3Csvg%20xmlns%3D%22http%3A%2F%2Fwww.w3.org%2F2000%2Fsvg%22%20width%3D%22120%22%20height%3D%2280%22%3E%3Crect%20width%3D%22120%22%20height%3D%2280%22%20fill%3D%22blue%22%2F%3E%3C%2Fsvg%3E" alt="Resizable image"></main></body></html>') });
  await page.getByLabel("Canvas zoom").selectOption("100");
  const frame = page.frameLocator("iframe");
  const paragraph = frame.locator("p");
  await frame.getByText("Double click this text", { exact: true }).waitFor();
  await expect(page.locator("iframe")).toHaveCSS("pointer-events", "auto");
  const localText = await paragraph.evaluate(el => { const r=el.getBoundingClientRect(); return { x:r.x+40,y:r.y+8 }; });
  const iframeBox = await page.locator("iframe").boundingBox();
  const scale = await page.locator("iframe").evaluate(el => el.getBoundingClientRect().width / el.clientWidth);
  await page.mouse.dblclick(iframeBox.x + localText.x * scale, iframeBox.y + localText.y * scale);
  await expect(paragraph).toHaveAttribute("contenteditable", "true"); await paragraph.fill("Directly edited text"); await paragraph.press("Enter");
  await expect(paragraph).toHaveText("Directly edited text");
  await page.waitForTimeout(150);
  await paragraph.click({ position: { x: 10, y: 10 } });
  await expect(page.locator(".ve-inspect-heading .ve-badge")).toHaveText("<p>");
  const rect = await paragraph.boundingBox();
  await page.keyboard.down("Alt"); await page.mouse.move(rect.x + 10, rect.y + 10); await page.mouse.down(); await page.mouse.move(rect.x + 42, rect.y + 26, { steps: 4 }); await page.mouse.up(); await page.keyboard.up("Alt");
  await expect(paragraph).toHaveCSS("transform", /matrix/);
  assert.match(await paragraph.getAttribute("style"), /translate/);
  await page.waitForTimeout(150);
  await frame.locator("img").click(); await expect(page.locator(".ve-inspect-heading .ve-badge")).toHaveText("<img>");
  const handle = frame.locator('[data-vh-ui="selection"] > div'), handleRect = await handle.boundingBox();
  await page.mouse.move(handleRect.x + 5, handleRect.y + 5); await page.mouse.down(); await page.mouse.move(handleRect.x + 29, handleRect.y + 21, { steps: 4 }); await page.mouse.up();
  await expect(frame.locator("img")).toHaveCSS("width", "144px");
  await expect(frame.locator("img")).toHaveCSS("height", "96px");
  await page.waitForTimeout(150);
  const layer = page.locator(".ve-layer-selected");
  await layer.getByRole("button", { name: "Lock layer", exact: true }).click();
  await expect(page.getByLabel("width", { exact: true })).toBeDisabled();
  await layer.getByRole("button", { name: "Unlock layer", exact: true }).click();
  await expect(page.getByLabel("width", { exact: true })).toBeEnabled();
  await layer.getByRole("button", { name: "Toggle layer visibility", exact: true }).click();
  await expect(frame.locator("img")).toBeHidden();
  await layer.getByRole("button", { name: "Toggle layer visibility", exact: true }).click();
  await expect(frame.locator("img")).toBeVisible();
  await page.getByRole("button", { name: "Move before previous sibling", exact: true }).click();
  await expect(frame.locator("main > :first-child")).toHaveJSProperty("tagName", "IMG");
  await page.getByRole("button", { name: "Move after next sibling", exact: true }).click();
  await expect(frame.locator("main > :first-child")).toHaveJSProperty("tagName", "P");
  await page.getByRole("button", { name: "Select parent element", exact: true }).click();
  await expect(page.locator(".ve-inspect-heading .ve-badge")).toHaveText("<main>");
  process.stdout.write("PASS: double-click text editing, Alt-drag movement, resize handle, lock/unlock, hide/show, sibling reorder and parent selection.\n");
} finally { await browser.close(); }

